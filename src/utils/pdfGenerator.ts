import { StudentProfile } from '../types';

/**
 * Generates an official ProofSkill Candidate Passport PDF locally without any external APIs.
 * Creates a formatted PDF blob and triggers a browser download.
 */
export function downloadSkillPassportPDF(profile: StudentProfile, proofScore: number): void {
  const dateStr = profile.passportGeneratedDate || new Date().toISOString().split('T')[0];
  const filename = `ProofSkill_Passport_${profile.passportId || 'candidate'}.pdf`;

  // Build clean PDF 1.4 document stream locally
  const lines: string[] = [
    `%PDF-1.4`,
    `1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj`,
    `2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj`,
    `3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >> endobj`,
    `5 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >> endobj`,
    `6 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj`
  ];

  // Compose text content stream
  const contentStream: string[] = [];

  // Helper to add escaped PDF text
  const addText = (text: string, x: number, y: number, font = 'F2', size = 10, gray = 0) => {
    const escaped = text.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
    contentStream.push(`BT /${font} ${size} Tf ${gray} g ${x} ${y} Td (${escaped}) Tj ET`);
  };

  // Header Bar
  addText('PROOFSKILL OFFICIAL SKILL PASSPORT', 50, 740, 'F1', 18, 0.1);
  addText(`Passport ID: ${profile.passportId}  |  Generated: ${dateStr}`, 50, 722, 'F2', 9, 0.4);
  addText(`Evidence Proof Index: ${proofScore}/100`, 420, 722, 'F1', 11, 0.1);

  // Divider
  contentStream.push(`0.8 w 50 710 m 562 710 l S`);

  // Candidate Details
  addText(`Candidate: ${profile.name}`, 50, 685, 'F1', 14, 0);
  addText(`Headline: ${profile.headline || 'Software Engineer'}`, 50, 670, 'F2', 10, 0.3);
  addText(`College / University: ${profile.college || profile.university}`, 50, 652, 'F2', 10, 0.2);
  addText(`Course / Degree: ${profile.course || profile.degree} (Class of ${profile.graduationYear})`, 50, 638, 'F2', 10, 0.2);
  addText(`Location: ${profile.location || 'N/A'}  |  Email: ${profile.email}`, 50, 624, 'F2', 9, 0.3);

  // Section: Standardized Assessments
  contentStream.push(`0.5 w 50 610 m 562 610 l S`);
  addText('STANDARDIZED TECHNICAL ASSESSMENTS', 50, 595, 'F1', 11, 0.1);

  let currentY = 575;
  const passedAssessments = profile.assessmentResults.filter(r => r.passed);
  if (passedAssessments.length === 0) {
    addText('No standardized assessments completed yet.', 60, currentY, 'F2', 9, 0.5);
    currentY -= 18;
  } else {
    passedAssessments.forEach(ass => {
      addText(`* ${ass.category || ass.skillName}: ${ass.score}% [${ass.skillLevel || 'Proficient'}] - Assessed ${ass.completedAt.split('T')[0]}`, 60, currentY, 'F2', 9, 0.15);
      currentY -= 16;
    });
  }

  // Section: Verified Project Evidence
  currentY -= 10;
  contentStream.push(`0.5 w 50 ${currentY + 12} m 562 ${currentY + 12} l S`);
  addText('PROJECT EVIDENCE LEDGER (SOURCE CODE & ARTIFACTS)', 50, currentY, 'F1', 11, 0.1);
  currentY -= 20;

  if (profile.projects.length === 0) {
    addText('No project evidence submitted yet.', 60, currentY, 'F2', 9, 0.5);
    currentY -= 18;
  } else {
    profile.projects.forEach(proj => {
      addText(`* ${proj.title} (${proj.evidenceType || proj.category})`, 60, currentY, 'F1', 9.5, 0.1);
      currentY -= 14;
      addText(`  Repo: ${proj.githubUrl}`, 70, currentY, 'F2', 8.5, 0.3);
      currentY -= 12;
      const techList = (proj.technologies && proj.technologies.length > 0) ? proj.technologies.join(', ') : proj.skillsProved.join(', ');
      addText(`  Tech: ${techList}  |  Commits: ${proj.commitsCount || 0}`, 70, currentY, 'F2', 8.5, 0.3);
      currentY -= 16;
    });
  }

  // Section: Technical Skill Catalog
  currentY -= 6;
  contentStream.push(`0.5 w 50 ${currentY + 12} m 562 ${currentY + 12} l S`);
  addText('SKILL INVENTORY & VERIFICATION LABELS', 50, currentY, 'F1', 11, 0.1);
  currentY -= 18;

  profile.skills.forEach(s => {
    let label = 'Self-Reported Claim';
    if (s.linkedProjectIds && s.linkedProjectIds.length > 0) {
      label = 'Project Evidence Submitted';
    } else if (s.assessmentScore !== undefined) {
      label = `Assessment Completed (${s.assessmentScore}%)`;
    }
    addText(`- ${s.name} [${s.category}] · Level: ${s.level} · Status: ${label}`, 60, currentY, 'F2', 8.5, 0.2);
    currentY -= 14;
  });

  // Footer Disclaimer
  currentY = Math.max(50, currentY - 10);
  contentStream.push(`0.5 w 50 ${currentY + 15} m 562 ${currentY + 15} l S`);
  addText(`Digital Signature Hash: ${profile.verificationHash}`, 50, currentY, 'F2', 8, 0.4);
  addText('Generated by ProofSkill Client Ledger Protocol. Evidence verified via source code & assessments.', 50, currentY - 12, 'F2', 7.5, 0.5);

  const streamData = contentStream.join('\n');
  const streamLength = streamData.length;

  lines.push(`4 0 obj << /Length ${streamLength} >> stream\n${streamData}\nendstream\nendobj`);

  // Cross-reference table
  let currentOffset = 0;
  const xref: string[] = ['xref', '0 7', '0000000000 65535 f '];
  lines.forEach((obj, idx) => {
    if (idx === 0) {
      currentOffset = obj.length + 1;
    } else {
      const offsetStr = currentOffset.toString().padStart(10, '0');
      xref.push(`${offsetStr} 00000 n `);
      currentOffset += obj.length + 1;
    }
  });

  const finalPdf = `${lines.join('\n')}\n${xref.join('\n')}\ntrailer << /Size 7 /Root 1 0 R >>\nstartxref\n${currentOffset}\n%%EOF`;

  const blob = new Blob([finalPdf], { type: 'application/pdf' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
